#!/usr/bin/env python3
# 生成双字体表 -> app/src/main/cpp/error_page_font.h
#   ASCII 32..126: DroidSansMono, 8x16 单元格 (等宽, 适合日志/地址)
#   CJK:          Noto Serif SC (思源宋体), 16x16 单元格 (每行 2 字节)
# 字符集: ASCII 全量 + 源码中的 CJK 字符 (> U+2000)
# 用法: python3 tools/gen_font.py
import glob
import io
import os

import freetype

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
MONO_TTF = os.path.join(HERE, "fonts", "DroidSansMono.ttf")
SONG_TTF = os.path.join(HERE, "fonts", "NotoSerifSC-Regular.otf")
OUT = os.path.join(ROOT, "app", "src", "main", "cpp", "error_page_font.h")

ASCII_W, ASCII_H = 8, 16
CJK_W, CJK_H = 16, 16
FIRST, LAST = 32, 126
THRESHOLD = 100


def collect_cjk_chars():
    chars = set()
    pattern = os.path.join(ROOT, "app", "src", "main", "cpp", "*")
    for path in glob.glob(pattern):
        if not (path.endswith(".cpp") or path.endswith(".h")):
            continue
        s = io.open(path, encoding="utf-8").read()
        for ch in s:
            if ord(ch) > 0x2000:
                chars.add(ch)
    return sorted(chars)


def render_ascii(face):
    face.set_pixel_sizes(0, 14)
    glyphs = []
    for code in range(FIRST, LAST + 1):
        face.load_char(chr(code), freetype.FT_LOAD_RENDER)
        bmp = face.glyph.bitmap
        w, h = bmp.width, bmp.rows
        rows = []
        for y in range(ASCII_H):
            byte = 0
            sy = y - 3
            for x in range(ASCII_W):
                on = 0
                if 0 <= sy < h and 0 <= x < w:
                    if bmp.buffer[sy * w + x] > THRESHOLD:
                        on = 1
                byte |= on << (7 - x)
            rows.append(byte)
        glyphs.append(rows)
    return glyphs


def open_song_face():
    face = freetype.Face(SONG_TTF)
    # 15px: 墨迹 (14~16px) 放进取 16x16 单元格仍有居中余量
    face.set_pixel_sizes(0, 15)
    return face


def render_cjk_glyph(face, codepoint):
    if face.get_char_index(codepoint) == 0:
        return None
    face.load_char(chr(codepoint), freetype.FT_LOAD_RENDER)
    slot = face.glyph
    bmp = slot.bitmap
    w, h = bmp.width, bmp.rows
    # 水平: 墨迹在 16px 单元格中居中
    # 垂直: 基线对齐 (与 ASCII 字体的 row 13 基线一致, 中英混排不错位)
    x0 = (CJK_W - w) // 2 if w < CJK_W else 0
    y0 = 13 - slot.bitmap_top
    if y0 < 0:
        y0 = 0
    rows = []
    for y in range(CJK_H):
        b0 = 0
        b1 = 0
        sy = y - y0
        for x in range(CJK_W):
            on = 0
            if 0 <= sy < h:
                sx = x - x0
                if 0 <= sx < w:
                    if bmp.buffer[sy * w + sx] > THRESHOLD:
                        on = 1
            if x < 8:
                b0 |= on << (7 - x)
            else:
                b1 |= on << (15 - x)
        rows.append((b0, b1))
    return rows


def main():
    mono = freetype.Face(MONO_TTF)
    ascii_glyphs = render_ascii(mono)
    print("ascii glyphs: " + str(len(ascii_glyphs)))

    song = open_song_face()
    cjk_chars = collect_cjk_chars()
    cjk = []
    for ch in cjk_chars:
        rows = render_cjk_glyph(song, ord(ch))
        if rows is not None:
            cjk.append((ord(ch), rows))
    print("cjk glyphs: " + str(len(cjk)) + " (requested " + str(len(cjk_chars)) + ")")

    out = []
    out.append("// Auto-generated by tools/gen_font.py. DO NOT EDIT.")
    out.append("// ASCII 8x16: DroidSansMono | CJK 16x16: Noto Serif SC (Song)")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace font8x16 {")
    out.append("")
    out.append("static const int kFirstChar = " + str(FIRST) + ";")
    out.append("static const int kLastChar = " + str(LAST) + ";")
    out.append("static const int kCharW = " + str(ASCII_W) + ";")
    out.append("static const int kCharH = " + str(ASCII_H) + ";")
    out.append("")
    out.append("// [char][row], 1 byte per row, bit7 = leftmost pixel")
    out.append("static const uint8_t kGlyphs[" + str(LAST - FIRST + 1) + "][" + str(ASCII_H) + "] = {")
    for code in range(FIRST, LAST + 1):
        rows = ascii_glyphs[code - FIRST]
        hexes = ", ".join("0x%02x" % b for b in rows)
        ch = chr(code)
        label = ch if 33 <= code <= 126 else " "
        out.append("    { " + hexes + " },  // '" + label + "'")
    out.append("};")
    out.append("")
    out.append("// ---- CJK 16x16, 2 bytes per row, bit15 = leftmost pixel ----")
    out.append("struct CjkGlyph {")
    out.append("    uint16_t code;")
    out.append("    uint8_t rows[16][2];")
    out.append("};")
    out.append("static const int kCjkCount = " + str(len(cjk)) + ";")
    out.append("static const CjkGlyph kCjkGlyphs[" + str(len(cjk)) + "] = {")
    for code, rows in cjk:
        row_strs = []
        for b0, b1 in rows:
            row_strs.append("{0x%02x,0x%02x}" % (b0, b1))
        out.append("    { 0x%04x, { %s } }," % (code, ", ".join(row_strs)))
    out.append("};")
    out.append("")
    out.append("}  // namespace font8x16")
    out.append("")

    with io.open(OUT, "w", encoding="utf-8") as f:
        f.write(os.linesep.join(out))
    print("written " + OUT)


if __name__ == "__main__":
    main()
